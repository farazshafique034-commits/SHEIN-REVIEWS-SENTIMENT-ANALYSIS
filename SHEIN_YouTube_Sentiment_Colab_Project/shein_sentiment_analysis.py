def youtube_get(endpoint: str, key: str, **params: Any) -> dict:
    """Make a documented YouTube Data API request; show safe error details."""
    url = API_BASE + endpoint
    args = dict(params)
    args["key"] = key
    try:
        resp = requests.get(url, params=args, timeout=35)
    except requests.RequestException as exc:
        raise YouTubeAPIError(f"Network error contacting YouTube: {type(exc).__name__}") from exc
    if not resp.ok:
        try:
            error = resp.json().get("error", {})
            reason = (error.get("errors") or [{}])[0].get("reason", "unknown")
            message = error.get("message", "API request failed")
        except (ValueError, AttributeError, IndexError, TypeError):
            reason, message = "unknown", f"HTTP {resp.status_code}"
        raise YouTubeAPIError(f"YouTube API HTTP {resp.status_code} [{reason}]: {message}")
    try:
        return resp.json()
    except ValueError as exc:
        raise YouTubeAPIError("YouTube returned an unexpected response") from exc


def extract_video_id(video_url_or_id: str) -> str | None:
    s = video_url_or_id.strip()
    if re.fullmatch(r"[a-zA-Z0-9_-]{11}", s):
        return s
    match = re.search(r"(?:youtube\.com/(?:watch\?[^\s]*?v=|shorts/|embed/)|youtu\.be/)([A-Za-z0-9_-]{11})", s)
    return match.group(1) if match else None


def read_video_urls(path: str | Path | None) -> list[str]:
    if not path or not Path(path).is_file():
        return []
    values = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            values.append(line)
    return values


def discover_video_ids(key: str, queries: list[str], max_candidates: int = 80) -> list[str]:
    """Discover public video IDs via search.list (not HTML scraping)."""
    ids: list[str] = []
    seen: set[str] = set()
    for query in queries:
        if len(ids) >= max_candidates:
            break
        result = youtube_get(
            "search", key, part="snippet", q=query, type="video",
            order="relevance", maxResults=25, safeSearch="moderate"
        )
        for item in result.get("items", []):
            video_id = item.get("id", {}).get("videoId")
            if video_id and video_id not in seen:
                ids.append(video_id)
                seen.add(video_id)
            if len(ids) >= max_candidates:
                break
    return ids


def video_metadata(key: str, ids: list[str]) -> list[dict]:
    """Fetch video titles and comment counts to choose discussion-rich videos."""
    result: list[dict] = []
    for start in range(0, len(ids), 50):
        chunk = ids[start:start + 50]
        if not chunk:
            continue
        data = youtube_get("videos", key, part="snippet,statistics", id=",".join(chunk))
        for video in data.get("items", []):
            stats = video.get("statistics", {})
            snippet = video.get("snippet", {})
            result.append({
                "video_id": video["id"],
                "video_title": html.unescape(snippet.get("title", "Untitled")),
                "comment_count": int(stats.get("commentCount", 0)),
                "video_channel": snippet.get("channelTitle", ""),
                "video_published": snippet.get("publishedAt", ""),
            })
    return result


def collect_comments(
    key: str, target_raw: int = 2700, max_videos: int = 35,
    queries: list[str] | None = None, manual_videos: list[str] | None = None,
) -> pd.DataFrame:
    """Collect public top-level comments; skip disabled-comment videos."""
    queries = queries or DEFAULT_QUERIES
    requested_ids = [extract_video_id(x) for x in (manual_videos or [])]
    requested_ids = [x for x in requested_ids if x]
    if not requested_ids:
        print("Searching YouTube for SHEIN clothing-review videos...")
        requested_ids = discover_video_ids(key, queries, max_candidates=max(max_videos * 2, 50))
    if not requested_ids:
        raise RuntimeError("No matching public videos found. Add review video URLs to VIDEO_URLS.txt.")

    metadata = video_metadata(key, list(dict.fromkeys(requested_ids)))
    # In manual mode, retain the exact user-provided order; otherwise sort by comments.
    if manual_videos:
        priority = {vid: i for i, vid in enumerate(requested_ids)}
        metadata.sort(key=lambda x: priority.get(x["video_id"], 10_000))
    else:
        metadata.sort(key=lambda x: x["comment_count"], reverse=True)
    metadata = [v for v in metadata if v["comment_count"] > 0][:max_videos]
    if not metadata:
        raise RuntimeError("No selected public videos have accessible comment counts.")

    records: list[dict] = []
    seen_comments: set[str] = set()
    for idx, video in enumerate(metadata, 1):
        if len(records) >= target_raw:
            break
        video_id = video["video_id"]
        page_token = None
        before = len(records)
        while len(records) < target_raw:
            kwargs = {
                "part": "snippet", "videoId": video_id, "maxResults": 100,
                "order": "relevance", "textFormat": "plainText",
            }
            if page_token:
                kwargs["pageToken"] = page_token
            try:
                payload = youtube_get("commentThreads", key, **kwargs)
            except YouTubeAPIError as exc:
                msg = str(exc).lower()
                if any(term in msg for term in ["commentsdisabled", "videonotfound", "disabled comments", "forbidden"]):
                    print(f"  Skipped a video with unavailable comments: {video_id}")
                    break
                raise
            for item in payload.get("items", []):
                top = item.get("snippet", {}).get("topLevelComment", {})
                comment_id = top.get("id", "")
                snip = top.get("snippet", {})
                original = snip.get("textOriginal", "") or snip.get("textDisplay", "")
                if not comment_id or not original or comment_id in seen_comments:
                    continue
                seen_comments.add(comment_id)
                records.append({
                    "comment_id": comment_id,
                    "video_id": video_id,
                    "video_title": video["video_title"],
                    "video_url": f"https://www.youtube.com/watch?v={video_id}",
                    "published_at": snip.get("publishedAt", ""),
                    "like_count": int(snip.get("likeCount", 0)),
                    "comment_text": original,
                })
                if len(records) >= target_raw:
                    break
            page_token = payload.get("nextPageToken")
            if not page_token:
                break
        print(f"  Video {idx}/{len(metadata)}: {len(records) - before} comments; total {len(records)}")
    return pd.DataFrame(records, columns=[
        "comment_id", "video_id", "video_title", "video_url",
        "published_at", "like_count", "comment_text",
    ])

"""## Step 5: Clean comments and split mixed opinions

Duplicates, obvious noise, and very short text are removed. Comments are split at sentence punctuation and contrast words (for example, *but*, *however*). These rules are useful but not perfect.
"""

def normalize_comment(text: str) -> str:
    text = html.unescape(str(text))
    text = re.sub(r"https?://\S+|www\.\S+", "", text)
    text = re.sub(r"@[\w.-]+", "@user", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def clean_comments(raw: pd.DataFrame, target: int = 2000) -> pd.DataFrame:
    """Keep substantive comments; duplicates/spam are discarded."""
    if raw.empty:
        return raw.copy()
    df = raw.copy()
    df["clean_text"] = df["comment_text"].fillna("").map(normalize_comment)
    df = df[df["clean_text"].str.len().between(12, 1500)]
    df = df[df["clean_text"].map(lambda t: len(re.findall(r"\b\w+\b", t)) >= 3)]
    df = df[~df["clean_text"].str.contains(
        r"^(?:first|nice video|great vlog|new subscriber|subscribe to my|check my channel)[!. ]*$",
        case=False, na=False, regex=True,
    )]
    df = df.drop_duplicates(subset=["comment_id"])
    df["_dedup"] = df["clean_text"].str.casefold()
    df = df.drop_duplicates(subset=["_dedup"]).drop(columns=["_dedup"])
    # Transparent, heuristic measure only: it is not an AI relevance classifier.
    topic_pattern = r"\b(?:shein|dress|clothes|clothing|top|pants|fabric|size|fit|material|outfit|haul|order|shipping|quality|shirt|skirt|jacket|delivery)\b"
    df["has_product_keyword"] = df["clean_text"].str.contains(topic_pattern, case=False, regex=True)
    return df.head(target).reset_index(drop=True)


def split_opinions(text: str) -> list[str]:
    """Split by sentences and common contrast words to reveal mixed opinions."""
    pieces = re.split(
        r"(?<=[.!?])\s+|(?:,\s*)?\b(?:but|however|although|though|yet|nevertheless|on the other hand)\b[,:]?\s*",
        text, flags=re.IGNORECASE,
    )
    clean = [p.strip(" \t\n,;:.-") for p in pieces if p.strip(" \t\n,;:.-")]
    # Tiny fragments are likely meaningless to the classifier: merge with adjacent.
    merged: list[str] = []
    for piece in clean:
        if merged and len(piece.split()) < 2:
            merged[-1] += " " + piece
        else:
            merged.append(piece)
    return merged[:12] if merged else [text]

"""## Step 6: AI prediction

RoBERTa predicts each opinion segment as **positive**, **negative**, or **neutral**. If a comment has both positive and negative segments, its derived overall label becomes **mixed**.

Example: *"Great dress, but poor fabric. Love the fitting!"* → individual segments may be **positive / negative / positive** → **mixed**.
"""

def init_model():
    """Load a public pretrained English RoBERTa model (no HF API key needed)."""
    from transformers import pipeline
    import torch
    device = 0 if torch.cuda.is_available() else -1
    print(f"Loading pretrained sentiment model ({'GPU' if device == 0 else 'CPU'})...")
    return pipeline("text-classification", model=MODEL_NAME, tokenizer=MODEL_NAME, device=device)


def analyze_sentiments(df: pd.DataFrame, classifier, batch_size: int = 24) -> pd.DataFrame:
    """Perform segment sentiment analysis and derive an additional Mixed label."""
    if df.empty:
        raise RuntimeError("No clean comments to analyze")
    output = df.copy()
    segments_by_comment = [split_opinions(t) for t in output["clean_text"].tolist()]
    flat_segments = [part for parts in segments_by_comment for part in parts]
    results: list[dict] = []
    for start in range(0, len(flat_segments), batch_size):
        batch = flat_segments[start:start + batch_size]
        preds = classifier(batch, truncation=True, max_length=256, batch_size=batch_size)
        if isinstance(preds, dict):
            preds = [preds]
        results.extend(preds)
        if start and start % (batch_size * 20) == 0:
            print(f"  Processed {min(start + batch_size, len(flat_segments))}/{len(flat_segments)} opinion segments")
    cursor = 0
    labels = []
    positives = []
    negatives = []
    neutrals = []
    details = []
    mean_confidences = []
    for segments in segments_by_comment:
        current_preds = results[cursor:cursor + len(segments)]
        cursor += len(segments)
        item_labels = []
        item_details = []
        for segment, pred in zip(segments, current_preds):
            pred_label = str(pred["label"]).lower().strip()
            if pred_label not in {"positive", "negative", "neutral"}:
                # Expected model labels are spelled out in its model card.
                pred_label = {"label_0": "negative", "label_1": "neutral", "label_2": "positive"}.get(pred_label, "neutral")
            score = float(pred["score"])
            # Low-certainty predictions are marked neutral as a conservative choice.
            label = pred_label if score >= 0.50 else "neutral"
            item_labels.append(label)
            item_details.append({"text": segment, "sentiment": label, "confidence": round(score, 3)})
        counts = Counter(item_labels)
        if counts["positive"] and counts["negative"]:
            whole = "mixed"
        elif counts["positive"]:
            whole = "positive"
        elif counts["negative"]:
            whole = "negative"
        else:
            whole = "neutral"
        labels.append(whole)
        positives.append(counts["positive"])
        negatives.append(counts["negative"])
        neutrals.append(counts["neutral"])
        details.append(json.dumps(item_details, ensure_ascii=False))
        mean_confidences.append(round(sum(x["confidence"] for x in item_details) / len(item_details), 3))
    output["sentiment"] = labels
    output["positive_segments"] = positives
    output["negative_segments"] = negatives
    output["neutral_segments"] = neutrals
    output["avg_model_confidence"] = mean_confidences
    output["segment_details_json"] = details
    return output

"""## Step 7: Charts and business report

The notebook saves a distribution plot, a video-level comparison, a keyword-based approximation of negative aspects, a review sheet you can fill in yourself, and an evidence-based marketing summary.
"""

def summarize_negative_aspects(analyzed: pd.DataFrame) -> dict[str, int]:
    counts = {key: 0 for key in ASPECT_PATTERNS}
    for entry in analyzed["segment_details_json"]:
        for segment in json.loads(entry):
            if segment["sentiment"] != "negative":
                continue
            sentence = segment["text"]
            for aspect, pattern in ASPECT_PATTERNS.items():
                if re.search(pattern, sentence, re.IGNORECASE):
                    counts[aspect] += 1
    return counts


