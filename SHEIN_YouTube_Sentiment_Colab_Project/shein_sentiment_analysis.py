"""## Step 8: End-to-end execution functions

Running the analysis later will automatically save raw comments to a CSV. When that raw CSV exists in this Colab session and `FORCE_REFRESH=False`, subsequent runs reuse the raw data and avoid unnecessary YouTube API requests.
"""

def run_project(
    target: int = 2000, output_dir: str | Path = "outputs",
    max_videos: int = 35, video_urls: list[str] | None = None,
    force_refresh: bool = False, search_queries: list[str] | None = None,
) -> pd.DataFrame:
    """End-to-end reproducible pipeline with collection cache."""
    folder = Path(output_dir)
    folder.mkdir(parents=True, exist_ok=True)
    raw_path = folder / "review_comments_raw.csv"
    clean_path = folder / "review_comments_clean.csv"
    if raw_path.is_file() and not force_refresh:
        print("Using cached raw comments (no additional YouTube API calls).")
        raw = pd.read_csv(raw_path, dtype={"comment_id": "string", "video_id": "string"})
    else:
        key = load_api_key()
        raw_target = max(target, int(target * 1.5))
        raw = collect_comments(
            key=key, target_raw=raw_target, max_videos=max_videos,
            queries=search_queries or DEFAULT_QUERIES, manual_videos=video_urls,
        )
        if raw.empty:
            raise RuntimeError("No YouTube comments collected. Try other videos or queries.")
        raw.to_csv(raw_path, index=False, encoding="utf-8-sig")
        print(f"Collected {len(raw)} raw comments")
    cleaned = clean_comments(raw, target=target)
    if cleaned.empty:
        raise RuntimeError("All collected comments were removed during cleaning")
    cleaned.to_csv(clean_path, index=False, encoding="utf-8-sig")
    print(f"Cleaned {len(cleaned)} comments from {len(raw)} raw records")
    classifier = init_model()
    analyzed = analyze_sentiments(cleaned, classifier)
    export_results(analyzed, folder, requested_target=target)
    return analyzed


